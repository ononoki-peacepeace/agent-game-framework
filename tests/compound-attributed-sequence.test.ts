import {afterEach,expect,it,vi} from 'vitest';
import {randomUUID} from 'node:crypto';
import {mkdtemp,readFile,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {narrativeWorldKinds,prepareNarrativeWorld} from './fixtures/narrative-worlds.js';
import {freeformCorpus,corpusProposal} from './fixtures/freeform-fixed-corpus.js';
import {JsonStore} from '../src/storage/json-store.js';
import {GameService} from '../src/server/service.js';
import {AIRuntime} from '../src/ai/runtime.js';
import {ProviderError} from '../src/ai/failures.js';
import {executePlan} from '../src/agent/executor.js';
import {validatePlan} from '../src/agent/planner.js';
import {agentPresentation} from '../src/client/agent-presentation.js';
import {SceneStory} from '../src/client/SceneStory.js';
import * as freeform from '../src/core/freeform.js';
import type {GoalInput} from '../src/agent/plan-schema.js';
afterEach(()=>vi.restoreAllMocks());
const run=randomUUID();
it.each(narrativeWorldKinds)('retains repeated attributed reactions around waiting in %s',async kind=>{
 const prepared=await prepareNarrativeWorld(kind),seed=structuredClone(prepared.save);
 for(const id of ['player','npc_lin'])seed.entities.find(e=>e.id===id)!.components.condition={hp:100,stamina:100,stress:0};
 seed.entities.find(e=>e.id==='npc_qiao')!.components.location={location_id:'station'};
 const sample=freeformCorpus.find(s=>s.id==='contact-miss')!,steps=[sample.input,'等一分钟',sample.input];
 const directory=await mkdtemp(join(tmpdir(),'agf-attributed-sequence-'));
 try{
  const store=new JsonStore(directory);await store.write(seed);
  const ai=new AIRuntime({name:'offline-sequence',generate:async()=>{throw Error('Unexpected generation');}});
  vi.spyOn(ai,'interpret').mockImplementation(async(_save,input)=>input===steps[1]?{type:'WAIT',parameters:{minutes:1}}:{type:'FREEFORM_ACTION',parameters:{}});
  vi.spyOn(ai,'freeform').mockResolvedValue(corpusProposal(sample));
  const narrate=vi.spyOn(ai,'narrate').mockRejectedValue(new ProviderError('refusal','offline-sequence','固定拒绝'));
  vi.spyOn(ai,'npcDecision').mockResolvedValue({kind:'speech',speech:'先停一下。',vote_target:null,intent:'表达意愿',proposed_action:null,evidence_refs:[],belief_updates:[],goal_updates:[],goal_proposals:[],plan_proposals:[],decision_summary:'只说这句话',social_response:null});
  const original=freeform.executeFreeform;let rngCalls=0;
  vi.spyOn(freeform,'executeFreeform').mockImplementation((...args)=>{const rolls=[...sample.rolls];args[4]=()=>{rngCalls++;return rolls.shift()!;};return original(...args);});
  const service=new GameService(store,ai,seed.definition),before=await service.current();
  const request={input:steps.join('，再'),game_id:before.game_id,expected_revision:before.state_revision,request_id:randomUUID()};
  const goals:GoalInput[]=steps.map((text,index)=>({goal_id:'step'+index,type:'WORLD_ACTION',normalized_goal:text,depends_on:index?['step'+(index-1)]:[],target_entities:[],condition:null,branch:null,temporal_scope:{scope:'now',day_offset:0,window:'any'}}));
  const response=await executePlan(service,request,validatePlan({goals})),after=await service.current();
  const shown=agentPresentation(service.project(before),response);
  const html=renderToStaticMarkup(createElement(SceneStory,{view:response.view!,override:shown.storyOverride?.text??null,turns:shown.storyOverride?.turns,onSelectEntity:()=>{}}));
  const receipts=after.resolution_receipts!.filter(r=>!before.resolution_receipts?.some(old=>old.request_id===r.request_id));
  await writeFile(join(process.cwd(),'.agent-runtime/codex',`attributed-${run}-${kind}.json`),JSON.stringify({request,response,receipts,html},null,2));
  expect(response.plan?.status).toBe('completed');expect(receipts.filter(r=>r.physical_outcome)).toHaveLength(2);
  expect(receipts.filter(r=>r.physical_outcome).every(r=>!r.physical_outcome!.contact)).toBe(true);
  expect(after.entities.find(e=>e.id==='npc_lin')!.components.condition!.hp).toBe(100);
  expect(html.split('先停一下。')).toHaveLength(3);
  expect(html.split('未能建立接触')).toHaveLength(3);
  expect(html.indexOf('先停一下。')).toBeLessThan(html.indexOf('等了1分钟'));
  expect(html.lastIndexOf('先停一下。')).toBeGreaterThan(html.indexOf('等了1分钟'));
  expect(html).not.toMatch(/受伤|造成了伤害|同意|微笑/);
  const bytes=await readFile(join(directory,'current.json')),calls=[rngCalls,narrate.mock.calls.length];
  const fresh=new GameService(new JsonStore(directory),ai,seed.definition);
  for(let i=0;i<receipts.length;i++)await fresh.turn({game_id:before.game_id,expected_revision:before.state_revision,request_id:receipts[i].request_id,input:steps[i]});
  expect(await fresh.current()).toEqual(after);expect(await readFile(join(directory,'current.json'))).toEqual(bytes);expect([rngCalls,narrate.mock.calls.length]).toEqual(calls);
 }finally{await rm(directory,{recursive:true,force:true});}
},30000);
